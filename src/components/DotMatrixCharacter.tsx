interface DotMatrixCharacterProps {
  char: string;
  dotSizeClass?: string;
  dotColorClass?: string;
  gapClass?: string;
  className?: string;
}

export const DotMatrixCharacter = ({
  char,
  dotSizeClass = 'w-2 h-2 sm:w-2.5 sm:h-2.5 md:w-3 md:h-3',
  dotColorClass = 'bg-foreground',
  gapClass = 'gap-1 md:gap-1.5',
  className = '',
}: DotMatrixCharacterProps) => {
  const matrix = useMemo(() => {
    const uppercaseChar = char.toUpperCase();
    return BITMAP_FONT[uppercaseChar] || BITMAP_FONT[' '];
  }, [char]);

  return (
    <div
      className={`inline-grid grid-cols-5 ${gapClass} ${className} select-none`}
      style={{ transformStyle: 'preserve-3d' }}
    >
      {matrix.map((row, rIdx) =>
        row.split('').map((cell, cIdx) => (
          <div
            key={`${rIdx}-${cIdx}`}
            className={`dot-matrix-dot rounded-full transition-transform duration-100 ${dotSizeClass} ${
              cell === '1' ? `${dotColorClass} opacity-100` : 'opacity-0'
            }`}
          />
        ))
      )}
    </div>
  );
};

export default DotMatrixCharacter;
